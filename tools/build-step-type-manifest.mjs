/**
 * Rebuilds catalogs/step-types/manifest.json from the definition files in that
 * folder (every *.json except schema.json, manifest.json and controls.json,
 * plus the action kinds in actions/),
 * and js/step-types/definitions.generated.js, the same definitions, schema and
 * control palette as one browser script so ATLAS has its registry as soon as
 * the page loads. It also writes the condition operators, as an engine script
 * and as the "operators" and "blockedOperators" of the File Utility contract.
 *
 *   npm run step-types:manifest           rewrite the files
 *   npm run step-types:manifest -- --check  fail when any is out of date
 *
 * Each entry records the id, version, file name and the SHA-256 of the
 * definition's canonical JSON, which the server compares against database
 * rows so a changed file can never overwrite a published version.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as prettier from "prettier";
import { documentHash } from "../src/canonical-json.js";

const DIR = new URL("../catalogs/step-types/", import.meta.url);
const MANIFEST = new URL("manifest.json", DIR);
const BUNDLE = new URL(
  "../js/step-types/definitions.generated.js",
  import.meta.url,
);
const OPERATORS = new URL(
  "../js/step-types/operators.generated.js",
  import.meta.url,
);
const CONTRACT = new URL(
  "../catalogs/file-utility/executable-steps.json",
  import.meta.url,
);
const RESERVED = new Set(["schema.json", "manifest.json", "controls.json"]);

const ACTIONS = "actions/";

function definitionFiles() {
  const json = (folder) =>
    readdirSync(new URL(folder, DIR)).filter((file) => file.endsWith(".json"));
  return [
    ...json("./")
      .filter((file) => !RESERVED.has(file))
      .sort(),
    ...json(ACTIONS)
      .sort()
      .map((file) => `${ACTIONS}${file}`),
  ];
}

const readJson = (file) => JSON.parse(readFileSync(new URL(file, DIR), "utf8"));

export function buildManifest() {
  const definitions = definitionFiles().map((file) => {
    const definition = readJson(file);
    const folder = definition.kind === "action" ? ACTIONS : "";
    const expected = new RegExp(
      `^${folder}${definition.id}(\\.v${definition.version})?\\.json$`,
    );
    if (!expected.test(file))
      throw new Error(
        `${file} holds "${definition.id}" version ${definition.version}; name it ${folder}${definition.id}.json or ${folder}${definition.id}.v${definition.version}.json`,
      );
    return {
      id: definition.id,
      version: definition.version,
      file,
      hash: documentHash(definition),
    };
  });
  const seen = new Set();
  definitions.forEach(({ id, version }) => {
    const key = `${id}@${version}`;
    if (seen.has(key))
      throw new Error(`${id} version ${version} is in two files`);
    seen.add(key);
  });
  return {
    $comment:
      "Generated by npm run step-types:manifest. Lists every definition file in this folder with its canonical-JSON SHA-256.",
    schemaVersion: 1,
    definitions,
  };
}

/**
 * The engine script that carries the condition operators of
 * catalogs/logic_phrase_catalog.json (app_config.logic_options
 * operator_catalog and operator_sets), for
 * ATLASStepTypes.conditions.operatorCatalog. It is an engine script, so the
 * Step Type Builder copies it with the rest of the engine.
 */
export async function buildOperators() {
  const catalog = JSON.parse(
    readFileSync(
      new URL("../catalogs/logic_phrase_catalog.json", import.meta.url),
      "utf8",
    ),
  );
  const options = catalog.app_config.logic_options;
  const operators = {
    catalog: options.operator_catalog,
    sets: options.operator_sets,
  };
  const source = `/**
 * Generated by \`npm run step-types:manifest\` from
 * catalogs/logic_phrase_catalog.json (app_config.logic_options).
 * Do not edit: change the phrase catalog and run the command again.
 *
 * The condition operators, read by ATLASStepTypes.conditions.operatorCatalog
 * when it is not given the phrase catalog.
 */
(function bundleConditionOperators(global) {
  "use strict";
  global.ATLASStepTypes = global.ATLASStepTypes || {};
  global.ATLASStepTypes.operators = ${JSON.stringify(operators)};
})(typeof window !== "undefined" ? window : globalThis);
`;
  const path = fileURLToPath(OPERATORS);
  const config = (await prettier.resolveConfig(path)) || {};
  return prettier.format(source, { ...config, filepath: path });
}

// File Utility's name for each operator meaning (procedures_v3 condition
// operators). A meaning not listed here has no File Utility code yet.
const FILE_UTILITY_COMPARE = {
  "=": "equals",
  "<>": "notEquals",
  ">": "gt",
  ">=": "gte",
  "<": "lt",
  "<=": "lte",
};
const FILE_UTILITY_TEXT_MATCH = {
  contains: ["contains", "notContains"],
  starts: ["startsWith", "notStartsWith"],
  ends: ["endsWith", "notEndsWith"],
};

/** File Utility's code for an operator catalog entry, or null. */
export function fileUtilityOperator(entry) {
  const meaning = entry?.meaning;
  if (!meaning) return null;
  if (meaning.compare != null)
    return FILE_UTILITY_COMPARE[meaning.compare] || null;
  if (meaning.text_match) {
    const pair = FILE_UTILITY_TEXT_MATCH[meaning.text_match.kind];
    return pair ? pair[meaning.text_match.negated ? 1 : 0] : null;
  }
  if (meaning.blank != null) return meaning.blank ? "notBlank" : "blank";
  return null;
}

/**
 * The File Utility contract with its "operators" (every value, alias and
 * formula alias in the operator catalog, mapped to File Utility's code) and
 * "blockedOperators" (the catalog values without one) rewritten. The rest
 * of the file is kept byte for byte, since File Utility holds an identical
 * copy.
 */
export function buildContract() {
  const catalog = JSON.parse(
    readFileSync(
      new URL("../catalogs/logic_phrase_catalog.json", import.meta.url),
      "utf8",
    ),
  );
  const entries = catalog.app_config.logic_options.operator_catalog.filter(
    (entry) => entry && entry.value,
  );
  const operators = [];
  const blocked = [];
  const seen = new Set();
  entries.forEach((entry) => {
    const code = fileUtilityOperator(entry);
    if (!code) {
      blocked.push(entry.value);
      return;
    }
    [entry.value, ...(entry.aliases || []), ...(entry.formulaAliases || [])]
      .map((name) => String(name).toLowerCase())
      .forEach((name) => {
        if (seen.has(name)) return;
        seen.add(name);
        operators.push(`    ${JSON.stringify(name)}: ${JSON.stringify(code)}`);
      });
  });
  const contract = readFileSync(CONTRACT, "utf8");
  const replace = (text, pattern, value, key) => {
    if (!pattern.test(text))
      throw new Error(
        `catalogs/file-utility/executable-steps.json has no "${key}" to rewrite.`,
      );
    return text.replace(pattern, value);
  };
  return replace(
    replace(
      contract,
      /"operators": \{[^}]*\}/,
      `"operators": {\n${operators.join(",\n")}\n  }`,
      "operators",
    ),
    /"blockedOperators": \[[^\]]*\]/,
    `"blockedOperators": ${JSON.stringify(blocked).replace(/","/g, '", "')}`,
    "blockedOperators",
  );
}

/**
 * The browser script that carries the schema and every definition the
 * manifest lists, formatted the way the pre-commit hook formats it.
 */
export async function buildBundle(manifest = buildManifest()) {
  const bundle = {
    schema: readJson("schema.json"),
    controls: readJson("controls.json"),
    definitions: manifest.definitions.map((entry) => readJson(entry.file)),
  };
  const source = `/**
 * Generated by \`npm run step-types:manifest\` from catalogs/step-types/.
 * Do not edit: change the definition files and run the command again.
 *
 * The step type schema, control palette and definitions as one script, so
 * the registry is ready as soon as js/13a-step-type-runtime.js runs.
 */
(function bundleStepTypeDefinitions(global) {
  "use strict";
  global.ATLASStepTypes = global.ATLASStepTypes || {};
  global.ATLASStepTypes.bundled = ${JSON.stringify(bundle)};
})(typeof window !== "undefined" ? window : globalThis);
`;
  const path = fileURLToPath(BUNDLE);
  const config = (await prettier.resolveConfig(path)) || {};
  return prettier.format(source, { ...config, filepath: path });
}

const isMain =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const manifest = buildManifest();
  const next = `${JSON.stringify(manifest, null, 2)}\n`;
  const bundle = await buildBundle(manifest);
  const operators = await buildOperators();
  const contract = buildContract();
  const read = (url) => {
    try {
      return readFileSync(url, "utf8");
    } catch {
      return "";
    }
  };
  if (process.argv.includes("--check")) {
    const stale = [
      read(MANIFEST) !== next && "catalogs/step-types/manifest.json",
      read(BUNDLE) !== bundle && "js/step-types/definitions.generated.js",
      read(OPERATORS) !== operators && "js/step-types/operators.generated.js",
      read(CONTRACT) !== contract &&
        "catalogs/file-utility/executable-steps.json",
    ].filter(Boolean);
    if (stale.length) {
      console.error(
        `${stale.join(", ")} ${stale.length > 1 ? "are" : "is"} out of date. Run \`npm run step-types:manifest\`.`,
      );
      process.exit(1);
    }
    console.log(
      "Step type manifest, bundle, operators and contract operators are up to date.",
    );
  } else {
    writeFileSync(MANIFEST, next);
    writeFileSync(BUNDLE, bundle);
    writeFileSync(OPERATORS, operators);
    writeFileSync(CONTRACT, contract);
    console.log(
      `Wrote catalogs/step-types/manifest.json, js/step-types/definitions.generated.js (${manifest.definitions.length} definitions), js/step-types/operators.generated.js and the operators in catalogs/file-utility/executable-steps.json.`,
    );
  }
}
