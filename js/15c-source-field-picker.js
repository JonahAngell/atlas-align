/**
 * User-facing label for a step object (by step_type) or a legacy step type
 * string such as "if" or "create". The only definition of this global.
 */
function stepTypeLabel(stepOrType) {
  if (stepOrType && typeof stepOrType === "object") {
    return (
      (STEP_TYPE_OPTIONS || []).find(
        ([value]) => value === stepOrType.step_type,
      )?.[1] ||
      stepOrType.step_type ||
      "Logic Step"
    );
  }
  const legacyLabels = {
    source: "Source",
    create: "Create Field",
    if: "If / Then",
    compare: "Compare",
    join: "Join",
    transform: "Manipulation",
  };
  return legacyLabels[stepOrType] || stepOrType || "Logic Step";
}
function renderLiveSourceOptions(selected = "") {
  const sources = sourceCatalogEntries();
  const selectedSources = new Set(
    atlasSourcesMatchingLookup(sources, selected),
  );
  return [
    '<option value="">Select source file...</option>',
    ...sources.map((source) => {
      const key = atlasStableSourceKey(source) || source.sourceKey;
      return `<option value="${esc(key)}" ${selectedSources.has(source) ? "selected" : ""}>${esc(atlasSourceDisambiguatedLabel(source))}</option>`;
    }),
  ].join("");
}
function conditionsForLiveEditor(step) {
  const conditions = parseStepConditions?.(step) || [];
  if (conditions.length) return conditions;
  return [
    defaultGuidedCondition?.(step) || {
      id: uid("cond"),
      connector: "IF",
      sourceFile: step.source || step.params?.source_file || "",
      sourceAlias: "",
      fieldName: step.field || step.params?.field_name || "",
      operator: "is equal to",
      valueMode: "values",
      compareValue: "",
    },
  ];
}
function writeLiveConditions(step, conditions) {
  step.params = step.params || {};
  step.conditions = conditions.map((condition) => ({
    id: condition.id || uid("cond"),
    field: condition.fieldName || condition.field || "",
    operator: condition.operator || "is equal to",
    value: condition.compareValue || condition.value || "",
  }));
  step.params.conditions_json = JSON.stringify(conditions);
}

document.addEventListener(
  "change",
  (event) => {
    const liveParam = event.target.closest("[data-live-param]");
    const liveCondition = event.target.closest("[data-live-condition]");
    if (!liveParam && !liveCondition) return;
    const step = state.audit.steps.find(
      (item) => item.id === state.selectedStepId,
    );
    if (!step || step.autoGeneratedReference) return;
    step.params = step.params || {};
    if (liveParam) {
      const key = liveParam.dataset.liveParam;
      step.params[key] = liveParam.value;
      if (key === "source_file") {
        step.source = liveParam.value;
        step.params.source_alias =
          sourceAliasFor?.(liveParam.value) || liveParam.value;
        const conditions = conditionsForLiveEditor(step);
        conditions[0].sourceFile = liveParam.value;
        conditions[0].sourceAlias = step.params.source_alias;
        writeLiveConditions(step, conditions);
      }
      if (key === "field_name") {
        step.field = liveParam.value;
        const conditions = conditionsForLiveEditor(step);
        conditions[0].fieldName = liveParam.value;
        writeLiveConditions(step, conditions);
      }
    }
    if (liveCondition) {
      const key = liveCondition.dataset.liveCondition;
      const conditions = conditionsForLiveEditor(step);
      conditions[0][key] =
        key === "compareValue"
          ? valuesToLines(liveCondition.value)
          : liveCondition.value;
      writeLiveConditions(step, conditions);
      if (key === "compareValue")
        step.params.compare_value = valuesToLines(liveCondition.value);
      if (key === "operator") step.params.operator = liveCondition.value;
    }
    normalizeCatalogStep?.(step);
    renderAll();
    scheduleAutosave();
  },
  true,
);

document.addEventListener(
  "input",
  (event) => {
    const liveField = event.target.closest(
      '[data-live-param="then_action"], [data-live-condition="compareValue"]',
    );
    if (!liveField) return;
    const step = state.audit.steps.find(
      (item) => item.id === state.selectedStepId,
    );
    if (!step || step.autoGeneratedReference) return;
    step.params = step.params || {};
    if (liveField.dataset.liveParam === "then_action") {
      step.params.then_action = liveField.value;
      step.action = liveField.value;
    }
    if (liveField.dataset.liveCondition === "compareValue") {
      const conditions = conditionsForLiveEditor(step);
      conditions[0].compareValue = valuesToLines(liveField.value);
      writeLiveConditions(step, conditions);
      step.params.compare_value = valuesToLines(liveField.value);
    }
    renderSelectedStep();
    renderPreview();
    renderLogicTablePreviewRows();
    scheduleAutosave();
  },
  true,
);

document.addEventListener("click", (event) => {
  const stepTypeButton = event.target.closest("[data-live-step-type]");
  if (stepTypeButton) {
    const step = state.audit.steps.find(
      (item) => item.id === state.selectedStepId,
    );
    if (!step || step.autoGeneratedReference) return;
    step.step_type = stepTypeButton.dataset.liveStepType;
    step.type = legacyTypeFromStepType?.(step.step_type) || step.type;
    step.params = {};
    if (
      !["if_then", "else", "filter_rows", "flag_records"].includes(
        step.step_type,
      )
    )
      step.conditions = [];
    normalizeCatalogStep?.(step);
    renderAll();
    scheduleAutosave();
    return;
  }
  const tableRow = event.target.closest("[data-table-step-id]");
  if (tableRow) {
    state.selectedStepId = tableRow.dataset.tableStepId;
    renderSteps();
    renderSelectedStep();
  }
});
