function stepTypeLabel(step) {
  return (
    (STEP_TYPE_OPTIONS || []).find(
      ([value]) => value === step.step_type,
    )?.[1] ||
    step.step_type ||
    "Logic Step"
  );
}
function renderLiveSourceOptions(selected = "") {
  const sources = sourceCatalogEntries();
  const selectedSources = new Set(
    atlasSourcesMatchingLookup(sources, selected),
  );
  return [
    '<option value="">Select source file...</option>',
    ...sources.map((source) => {
      const key = atlasStableSourceKey(source) || source.sourceKey;
      return `<option value="${esc(key)}" ${selectedSources.has(source) ? "selected" : ""}>${esc(atlasSourceDisambiguatedLabel(source))}</option>`;
    }),
  ].join("");
}
function renderLiveFieldOptions(sourceFile = "", selected = "") {
  const fields = fieldsForSource(sourceFile);
  return [
    '<option value="">Select field...</option>',
    ...fields.map((field) => {
      const raw = field.fieldName || field.name || field.label || "";
      const vanity = field.vanityLabel || field.label || raw;
      return `<option value="${esc(raw)}" ${selected === raw || selected === vanity ? "selected" : ""}>${esc(raw)}${vanity && vanity !== raw ? ` (${esc(vanity)})` : ""}</option>`;
    }),
  ].join("");
}
function conditionsForLiveEditor(step) {
  const conditions = parseStepConditions?.(step) || [];
  if (conditions.length) return conditions;
  return [
    defaultGuidedCondition?.(step) || {
      id: uid("cond"),
      connector: "IF",
      sourceFile: step.source || step.params?.source_file || "",
      sourceAlias: "",
      fieldName: step.field || step.params?.field_name || "",
      operator: "is equal to",
      valueMode: "values",
      compareValue: "",
    },
  ];
}
function writeLiveConditions(step, conditions) {
  step.params = step.params || {};
  step.conditions = conditions.map((condition) => ({
    id: condition.id || uid("cond"),
    field: condition.fieldName || condition.field || "",
    operator: condition.operator || "is equal to",
    value: condition.compareValue || condition.value || "",
  }));
  step.params.conditions_json = JSON.stringify(conditions);
}
function renderLiveCriteriaEditor(step) {
  if (!step || step.autoGeneratedReference) {
    return '<p class="hint">Generated reference steps are controlled by the selected source files. Remove or add source files from the Fields page to change generated reference steps.</p>';
  }
  normalizeCatalogStep?.(step);
  const p = step.params || {};
  const firstCondition = conditionsForLiveEditor(step)[0] || {};
  const activeSource =
    p.source_file || firstCondition.sourceFile || step.source || "";
  const activeField =
    p.field_name || firstCondition.fieldName || step.field || "";
  return `<div class="live-criteria-editor">
    <div class="field-row full"><span>Step Type</span><div class="step-type-pill-row live-step-type-row">${(
      STEP_TYPE_OPTIONS || []
    )
      .filter(([value]) => value !== "reference_source")
      .map(
        ([value, label]) =>
          `<button type="button" class="step-type-pill ${step.step_type === value ? "active" : ""}" data-live-step-type="${esc(value)}">${esc(label)}</button>`,
      )
      .join("")}</div></div>
    <label class="field-row"><span>Source File</span><select data-live-param="source_file">${renderLiveSourceOptions(activeSource)}</select></label>
    <label class="field-row"><span>Field Name</span><select data-live-param="field_name">${renderLiveFieldOptions(activeSource, activeField)}</select></label>
    <label class="field-row"><span>Operator</span><select data-live-condition="operator">${optionsHtml(
      catalogArrayFromOptions({
        path: "app_config.logic_options.operators",
        fallback: [
          "is equal to",
          "is not equal to",
          "contains",
          "does not contain",
          "is blank/null",
          "is not blank/null",
        ],
      }),
      firstCondition.operator || p.operator || "is equal to",
    )}</select></label>
    <label class="field-row full"><span>Compare Values <em class="small">one value per line</em></span><textarea data-live-condition="compareValue" class="value-list-textarea" placeholder="One value per line">${esc(valuesToLines(firstCondition.compareValue || p.compare_value || ""))}</textarea></label>
    <label class="field-row full"><span>THEN / Action Text</span><textarea data-live-param="then_action" placeholder="Describe the action for this step">${esc(p.then_action || step.action || "")}</textarea></label>
  </div>`;
}

renderSelectedStep = function renderSelectedStepLiveOutput() {
  const step = state.audit.steps.find(
    (item) => item.id === state.selectedStepId,
  );
  const target = e.selectedStepDetails || $("selectedStepDetails");
  if (!target) return;
  if (!step) {
    target.innerHTML =
      '<p class="hint">Select or create a step to edit criteria and preview standardized output.</p>';
    setText?.("selectedRuleBadge", "No rule selected");
    return;
  }
  const number = stepNumberFor(step.id) || "?";
  setText?.("selectedRuleBadge", `Step ${number}`);
  target.innerHTML = `<div class="live-output-heading"><div><span class="badge blue">Step ${esc(number)}</span><strong>${esc(stepTypeLabel(step))}</strong></div><span class="small">${step.autoGeneratedReference ? "Generated reference step" : "Editable rule"}</span></div><div class="callout logic-output-box"><strong>Generated Analyst Logic</strong><div class="logic-output-text">${renderLogicWithPills(analystLogic(step))}</div></div>${renderLiveCriteriaEditor(step)}`;
};

document.addEventListener(
  "change",
  (event) => {
    const liveParam = event.target.closest("[data-live-param]");
    const liveCondition = event.target.closest("[data-live-condition]");
    if (!liveParam && !liveCondition) return;
    const step = state.audit.steps.find(
      (item) => item.id === state.selectedStepId,
    );
    if (!step || step.autoGeneratedReference) return;
    step.params = step.params || {};
    if (liveParam) {
      const key = liveParam.dataset.liveParam;
      step.params[key] = liveParam.value;
      if (key === "source_file") {
        step.source = liveParam.value;
        step.params.source_alias =
          sourceAliasFor?.(liveParam.value) || liveParam.value;
        const conditions = conditionsForLiveEditor(step);
        conditions[0].sourceFile = liveParam.value;
        conditions[0].sourceAlias = step.params.source_alias;
        writeLiveConditions(step, conditions);
      }
      if (key === "field_name") {
        step.field = liveParam.value;
        const conditions = conditionsForLiveEditor(step);
        conditions[0].fieldName = liveParam.value;
        writeLiveConditions(step, conditions);
      }
    }
    if (liveCondition) {
      const key = liveCondition.dataset.liveCondition;
      const conditions = conditionsForLiveEditor(step);
      conditions[0][key] =
        key === "compareValue"
          ? valuesToLines(liveCondition.value)
          : liveCondition.value;
      writeLiveConditions(step, conditions);
      if (key === "compareValue")
        step.params.compare_value = valuesToLines(liveCondition.value);
      if (key === "operator") step.params.operator = liveCondition.value;
    }
    normalizeCatalogStep?.(step);
    renderAll();
    scheduleAutosave();
  },
  true,
);

document.addEventListener(
  "input",
  (event) => {
    const liveField = event.target.closest(
      '[data-live-param="then_action"], [data-live-condition="compareValue"]',
    );
    if (!liveField) return;
    const step = state.audit.steps.find(
      (item) => item.id === state.selectedStepId,
    );
    if (!step || step.autoGeneratedReference) return;
    step.params = step.params || {};
    if (liveField.dataset.liveParam === "then_action") {
      step.params.then_action = liveField.value;
      step.action = liveField.value;
    }
    if (liveField.dataset.liveCondition === "compareValue") {
      const conditions = conditionsForLiveEditor(step);
      conditions[0].compareValue = valuesToLines(liveField.value);
      writeLiveConditions(step, conditions);
      step.params.compare_value = valuesToLines(liveField.value);
    }
    renderSelectedStep();
    renderPreview();
    renderLogicTablePreviewRows();
    scheduleAutosave();
  },
  true,
);

document.addEventListener("click", (event) => {
  const stepTypeButton = event.target.closest("[data-live-step-type]");
  if (stepTypeButton) {
    const step = state.audit.steps.find(
      (item) => item.id === state.selectedStepId,
    );
    if (!step || step.autoGeneratedReference) return;
    step.step_type = stepTypeButton.dataset.liveStepType;
    step.type = legacyTypeFromStepType?.(step.step_type) || step.type;
    step.params = {};
    if (
      !["if_then", "else", "filter_rows", "flag_records"].includes(
        step.step_type,
      )
    )
      step.conditions = [];
    normalizeCatalogStep?.(step);
    renderAll();
    scheduleAutosave();
    return;
  }
  const tableRow = event.target.closest("[data-table-step-id]");
  if (tableRow) {
    state.selectedStepId = tableRow.dataset.tableStepId;
    renderSteps();
    renderSelectedStep();
  }
});
