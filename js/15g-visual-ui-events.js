/**
 * A new step of `stepType`, built from its definition and not yet added to
 * the audit: the type's label as its title, the defaults of the composites
 * it places (one blank condition, a Display action, or the unique Error
 * Message custom field as the action's column) and its field defaults.
 * Every way of adding a step uses it.
 * @param {string} stepType - Step type id.
 * @param {object} [options] - sourceFile and sourceAlias, parentId,
 *   branchType, sortOrder and the audit's fields.
 */
function atlasBuildNewStep(
  stepType,
  {
    sourceFile = "",
    sourceAlias = "",
    parentId = null,
    branchType = "root",
    sortOrder = 1,
    fields,
  } = {},
) {
  const alias = sourceFile
    ? sourceAlias || sourceAliasFor?.(sourceFile) || sourceFile
    : "";
  const step = {
    id: uid("step"),
    enabled: true,
    parentId,
    branchType,
    sortOrder,
    title: atlasNewRuleStepLabel(stepType),
    type: legacyTypeFromStepType?.(stepType) || "if",
    step_type: stepType,
    source: sourceFile,
    field: "",
    action: "",
    notes: "",
    conditions: [],
    params: sourceFile ? { source_file: sourceFile, source_alias: alias } : {},
  };
  const defaults = globalThis.ATLASStepTypeRuntime?.newStepDefaults?.(
    stepType,
  ) || { blankCondition: false, params: {} };
  normalizeCatalogStep?.(step);
  if ("then_action_type" in defaults.params) {
    delete step.params.then_action_type;
    atlasInitializeNewIfThenAction(step, fields);
  }
  Object.entries(defaults.params).forEach(([param, value]) => {
    if (step.params[param] === undefined || step.params[param] === "")
      step.params[param] = value;
  });
  if (defaults.blankCondition) {
    // normalize() may already have seeded the blank condition.
    let conditions = [];
    try {
      conditions = JSON.parse(step.params.conditions_json || "[]");
    } catch {
      conditions = [];
    }
    if (!Array.isArray(conditions) || !conditions.length)
      conditions = [
        defaultGuidedCondition?.(step) || {
          id: uid("cond"),
          connector: "IF",
          conditionType: "row_compare",
          sourceFile,
          sourceAlias: alias,
          fieldName: "",
          operator: "is equal to",
          valueMode: "values",
          compareValue: "",
        },
      ];
    if (sourceFile)
      conditions.forEach((condition) => {
        if (condition && !condition.sourceFile) {
          condition.sourceFile = sourceFile;
          condition.sourceAlias = alias;
        }
      });
    step.params.conditions_json = JSON.stringify(conditions);
    if (!step.conditions?.length)
      step.conditions = [
        { id: uid("cond"), field: "", operator: "is equal to", value: "" },
      ];
  }
  return step;
}
function atlasCreateRuleOfType(stepType, { afterStepId = "" } = {}) {
  const options = atlasNewRuleTypeOptions();
  const type = options.some(([value]) => value === stepType)
    ? stepType
    : options.some(([value]) => value === "if_then")
      ? "if_then"
      : options[0]?.[0] || "if_then";
  const step = atlasBuildNewStep(type, {
    sourceFile: atlasDefaultSourceForNewRule(),
    sortOrder: (state.audit.steps || []).length + 1,
  });
  const steps = state.audit.steps || [];
  const index = afterStepId
    ? steps.findIndex((item) => item.id === afterStepId)
    : -1;
  if (index >= 0) steps.splice(index + 1, 0, step);
  else steps.push(step);
  state.audit.steps = steps;
  atlasReindexManualRules();
  state.selectedStepId = step.id;
  atlasCloseNewRuleTypeMenu();
  atlasRequestStructuralStepRender?.();
  scheduleAutosave();
  status?.(`Added ${atlasNewRuleStepLabel(type)} rule.`, "ok");
  atlasRevealLogicStepPane?.();
  return step;
}
