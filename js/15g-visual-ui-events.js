document.addEventListener(
  "click",
  (event) => {
    const editorTab = event.target.closest("[data-editor-tab]");
    if (editorTab) {
      atlasLogicEditorTab = editorTab.dataset.editorTab || "";
      renderSelectedStep();
      return;
    }
    const addValue = event.target.closest("[data-add-condition-value]");
    if (addValue) {
      const editor = addValue.closest(".condition-values-editor");
      const list = editor?.querySelector(".condition-values-list");
      if (list)
        list.insertAdjacentHTML("beforeend", atlasConditionValueRows(""));
      atlasUpdateConditionValueHidden(editor);
      return;
    }
    const removeValue = event.target.closest("[data-remove-condition-value]");
    if (removeValue) {
      const editor = removeValue.closest(".condition-values-editor");
      const row = removeValue.closest(".condition-value-row");
      row?.remove();
      if (editor && !editor.querySelector("[data-condition-value-item]")) {
        editor
          .querySelector(".condition-values-list")
          ?.insertAdjacentHTML("beforeend", atlasConditionValueRows(""));
      }
      atlasUpdateConditionValueHidden(editor);
      atlasCommitLiveEditor?.({ rerender: false });
    }
  },
  true,
);

document.addEventListener(
  "input",
  (event) => {
    if (!event.target.matches("[data-condition-value-item]")) return;
    const editor = event.target.closest(".condition-values-editor");
    atlasUpdateConditionValueHidden(editor);
  },
  true,
);

document.addEventListener(
  "keydown",
  (event) => {
    const input = event.target.closest?.("[data-condition-value-item]");
    if (!input || (event.key !== "Enter" && event.key !== "Tab")) return;

    if (event.key === "Tab") {
      // Commit before the browser advances focus. Exact matching is intentional:
      // comparison values are case-sensitive, so "ABC" and "abc" are distinct.
      atlasCommitConditionValueInput(input, { clearDuplicate: true });
      return;
    }

    event.preventDefault();
    event.stopImmediatePropagation();
    const result = atlasCommitConditionValueInput(input);
    if (result.duplicate) {
      input.select();
      status?.("That exact comparison value is already listed.", "warn");
      return;
    }
    if (!result.committed) return;
    atlasFocusNextConditionValue(input, result.editor);
  },
  true,
);

/* Follow-up Logic Step Editor refinements */
function catalogOperatorLabel(path, fallback) {
  if (typeof getCatalogValue !== "function") return fallback;
  const value = getCatalogValue(path, undefined);
  return typeof value === "string" && value ? value : fallback;
}

/**
 * Action types offered for a THEN/ELSE action: the action kinds, in their
 * order, by their picker labels. A kind shown under another's choice (Do
 * Not Display under Display) is left out, and a legacy kind (Freeform Text,
 * which can't run in File Utility) is offered only to a step that already
 * uses it, unless the definition switched it off.
 * @param {string} current - The step's current action type.
 * @param {{freeform?: boolean}} [options] - freeform false drops the
 *   legacy choice.
 */
function atlasThenActionTypeChoices(current = "", { freeform = true } = {}) {
  const kinds = window.ATLASStepTypeRuntime?.actionKinds?.() || [];
  return kinds
    .filter(
      (kind) =>
        !kind.picker?.choice &&
        (!kind.picker?.legacy || (freeform && current === kind.name)),
    )
    .map((kind) => [
      kind.name,
      kind.picker?.label || kind.label,
      kind.picker?.description ?? kind.description ?? "",
    ]);
}

/**
 * Returns which records a Do Not Display action hides: "matching" (only the
 * records that meet the conditions) or "key" (every record that shares a
 * key value with a matching record).
 * @param {Record<string, any>} p - Step params.
 */
function atlasExcludeScope(p = {}) {
  return p?.then_exclude_scope === "key" ? "key" : "matching";
}

/**
 * Parses a JSON list param, returning [] when blank or invalid.
 * @param {any} raw - Stored value (array or JSON text).
 */
function atlasParseJsonList(raw) {
  if (Array.isArray(raw)) return raw;
  try {
    const parsed = JSON.parse(String(raw || "[]"));
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

/**
 * Returns the key field of a group exclude, from the editor fields or the
 * stored then_exclude_key_fields_json list.
 * @param {Record<string, any>} p - Step params.
 * @returns {{sourceFile: string, sourceAlias: string, fieldName: string}}
 */
function atlasExcludeKeyField(p = {}) {
  const stored = atlasParseJsonList(p?.then_exclude_key_fields_json)[0] || {};
  const fieldName = String(
    p?.then_exclude_key_field ?? stored.fieldName ?? "",
  ).trim();
  const sourceFile = String(
    p?.then_exclude_key_source_file || stored.sourceFile || "",
  ).trim();
  const sourceAlias = String(
    (sourceFile ? sourceAliasFor?.(sourceFile) : "") ||
      p?.then_exclude_key_source_alias ||
      stored.sourceAlias ||
      "",
  ).trim();
  return { sourceFile, sourceAlias, fieldName };
}

/**
 * The picker choice an action type shows as: the choice its kind is shown
 * under (Do Not Display shows as Display), else the type itself.
 * @param {string} actionType - The step's then_action_type.
 */
function atlasActionChoiceValue(actionType) {
  const kind = /^[a-z][a-z0-9_]*$/.test(actionType || "")
    ? window.ATLASStepTypeRuntime?.registry?.()?.get?.(`action_${actionType}`)
    : null;
  return (kind?.kind === "action" && kind.picker?.choice) || actionType;
}

