/* Compact viewport pane switch. Visibility is CSS-only so the editor DOM stays mounted. */
const atlasLogicPaneMedia = window.matchMedia("(max-width: 1100px)");

function atlasActivateLogicPane(pane, { focusPanel = false } = {}) {
  const page = document.getElementById("page-steps");
  if (!page) return;
  const tabs = [...page.querySelectorAll("[data-logic-pane-tab]")];
  const panels = [...page.querySelectorAll("[data-logic-pane]")];
  if (!tabs.length || !panels.length) return;
  const nextPane = pane === "step" ? "step" : "rules";
  page.dataset.logicPane = nextPane;
  tabs.forEach((tab) => {
    const selected = tab.dataset.logicPaneTab === nextPane;
    tab.setAttribute("aria-selected", selected ? "true" : "false");
    tab.tabIndex = selected ? 0 : -1;
  });
  panels.forEach((panel) => {
    panel.classList.toggle(
      "is-logic-pane-active",
      panel.dataset.logicPane === nextPane,
    );
  });
  if (focusPanel && atlasLogicPaneMedia.matches) {
    panels
      .find((panel) => panel.dataset.logicPane === nextPane)
      ?.focus({ preventScroll: true });
  }
}

function atlasRevealLogicStepPane() {
  atlasActivateLogicPane("step", { focusPanel: true });
}

function atlasBindLogicPaneSwitch() {
  const tablist = document.querySelector(
    "#page-steps [data-logic-pane-switch]",
  );
  if (!tablist || tablist.dataset.bound === "true") return;
  tablist.dataset.bound = "true";
  tablist.addEventListener("click", (event) => {
    const tab = event.target.closest("[data-logic-pane-tab]");
    if (!tab || !tablist.contains(tab)) return;
    atlasActivateLogicPane(tab.dataset.logicPaneTab);
  });
  tablist.addEventListener("keydown", (event) => {
    const tabs = [...tablist.querySelectorAll("[role='tab']")];
    const index = tabs.indexOf(document.activeElement);
    if (index < 0) return;
    let nextIndex = -1;
    if (event.key === "ArrowRight" || event.key === "ArrowDown")
      nextIndex = (index + 1) % tabs.length;
    else if (event.key === "ArrowLeft" || event.key === "ArrowUp")
      nextIndex = (index - 1 + tabs.length) % tabs.length;
    else if (event.key === "Home") nextIndex = 0;
    else if (event.key === "End") nextIndex = tabs.length - 1;
    if (nextIndex < 0) return;
    event.preventDefault();
    atlasActivateLogicPane(tabs[nextIndex].dataset.logicPaneTab);
    tabs[nextIndex].focus();
  });
}

atlasBindLogicPaneSwitch();

// Display and Do Not Display share one action card. The card stores "display";
// the Matching records toggle decides which of the two the step keeps.
const atlasCaptureGuidedFieldsBeforeDisplayToggle = atlasCaptureGuidedFields;
atlasCaptureGuidedFields = function atlasCaptureGuidedFieldsWithDisplayToggle(
  root,
  step,
) {
  atlasCaptureGuidedFieldsBeforeDisplayToggle(root, step);
  const params = step?.params;
  if (!params) return;
  const mode = params.then_display_mode;
  delete params.then_display_mode;
  if (params.then_action_type === "display") {
    if (mode === "do_not_display") params.then_action_type = "do_not_display";
    params.then_action =
      params.then_action_type === "do_not_display"
        ? "Do not display matching records"
        : "Display matching records";
  }
  atlasNormalizeExcludeScopeParams(params);
  if (step.step_type === "split_field") atlasNormalizeSplitFieldParams(params);
  if (step.step_type === "create_column")
    atlasNormalizeCreateColumnStructuredParams(params);
  if (step.step_type === "format_field")
    atlasNormalizeFormatFieldParams(params);
};

/**
 * Keeps the group exclude settings consistent. A "key" scope is kept only on
 * Do Not Display; its key field is mirrored into then_exclude_key_fields_json
 * (a JSON list of {sourceFile, sourceAlias, fieldName}) for the compiler.
 * @param {Record<string, any>} params - Step params, changed in place.
 */
function atlasNormalizeExcludeScopeParams(params) {
  if (!params) return params;
  const keys = [
    "then_exclude_scope",
    "then_exclude_key_field",
    "then_exclude_key_source_file",
    "then_exclude_key_source_alias",
    "then_exclude_key_fields_json",
  ];
  if (
    params.then_action_type !== "do_not_display" ||
    atlasExcludeScope(params) !== "key"
  ) {
    keys.forEach((key) => delete params[key]);
    return params;
  }
  const key = atlasExcludeKeyField(params);
  params.then_exclude_scope = "key";
  params.then_exclude_key_field = key.fieldName;
  params.then_exclude_key_source_file = key.sourceFile;
  params.then_exclude_key_source_alias = key.sourceAlias;
  params.then_exclude_key_fields_json = JSON.stringify(
    key.fieldName ? [key] : [],
  );
  params.then_action = "Do not display all records for this key";
  return params;
}
