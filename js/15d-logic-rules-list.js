function atlasStepTypeLabel(step) {
  return (
    (STEP_TYPE_OPTIONS || []).find(
      ([value]) => value === step.step_type,
    )?.[1] ||
    step.step_type ||
    "Logic Step"
  );
}
function atlasVisibleStepEntries() {
  return hierarchicalStepEntries({ includeDisabled: true });
}
function atlasEditorValue(root, selector, fallback = "") {
  const field = root.querySelector(selector);
  if (!field) return fallback;
  if (field.type === "checkbox") return field.checked;
  return field.value;
}
function atlasCaptureGuidedFields(root, step) {
  normalizeCatalogStep?.(step);
  step.params =
    step.params && typeof step.params === "object" ? step.params : {};
  root.querySelectorAll("[data-param]").forEach((input) => {
    const key = input.dataset.param;
    if (!key) return;
    step.params[key] =
      input.type === "checkbox" ? (input.checked ? "Yes" : "No") : input.value;
  });
  const conditionRows = [...root.querySelectorAll(".guided-condition-row")];
  if (conditionRows.length) {
    const conditions = conditionRows.map((row, index) => {
      const get = (field) =>
        row.querySelector(`[data-condition-field="${field}"]`)?.value || "";
      const sourceFile = get("sourceFile");
      const compareSourceFile = get("compareSourceFile") || sourceFile;
      return {
        id: row.dataset.conditionId || uid("cond"),
        connector: index === 0 ? "IF" : get("connector") || "AND",
        conditionType: "row_compare",
        sourceFile,
        sourceAlias: sourceAliasFor(sourceFile),
        fieldName: get("fieldName"),
        operator: get("operator") || "is equal to",
        valueMode: get("valueMode") || "values",
        compareValue: get("compareValue"),
        compareSourceFile,
        compareSourceAlias: sourceAliasFor(compareSourceFile),
        compareFieldName: get("compareFieldName"),
        expression: get("expression"),
      };
    });
    step.params.conditions_json = JSON.stringify(conditions);
    step.conditions = conditions.map((condition) => ({
      id: condition.id,
      field: condition.fieldName,
      operator: condition.operator,
      value: condition.compareValue,
    }));
  }
  if (step.params.source_file) {
    step.source = step.params.source_file;
    step.params.source_alias = sourceAliasFor(step.params.source_file);
  }
  if (step.params.field_name) step.field = step.params.field_name;
  if (step.params.column_name) step.field = step.params.column_name;
}
function atlasRefreshLogicRuleCard(step) {
  if (!step?.id) return;

  const card = document.querySelector(
    `.step-card[data-id="${CSS.escape(step.id)}"]`,
  );
  if (!card) return;

  const logicTarget = card.querySelector(
    ".compact-rule-logic, .logic-rule-summary",
  );
  if (logicTarget) {
    logicTarget.innerHTML = renderStepCardLogic(analystLogic(step));
  }

  card.classList.toggle("selected", state.selectedStepId === step.id);
}

function atlasCommitLiveEditor({ rerender = false } = {}) {
  const root = document.querySelector("[data-live-editor-step-id]");
  if (!root) return;
  const step = state.audit.steps.find(
    (item) => item.id === root.dataset.liveEditorStepId,
  );
  if (!step || step.autoGeneratedReference) return;
  const nextType = atlasEditorValue(
    root,
    "[data-live-step-type-select]",
    step.step_type || "if_then",
  );
  const typeChanged = nextType && nextType !== step.step_type;
  step.step_type = nextType;
  step.type = legacyTypeFromStepType?.(step.step_type) || step.type;
  if (typeChanged) {
    step.params = {};
    if (
      !["if_then", "else", "filter_rows", "flag_records"].includes(
        step.step_type,
      )
    )
      step.conditions = [];
    normalizeCatalogStep?.(step);
    if (typeof atlasRequestStructuralStepRender === "function") {
      atlasRequestStructuralStepRender();
    } else {
      renderSteps?.();
      renderSelectedStep?.();
      renderLogicTablePreviewRows?.();
      renderPreview?.();
      renderValidationPanel?.();
    }
    scheduleAutosave();
    return;
  }
  step.title = atlasEditorValue(
    root,
    "[data-live-step-title]",
    step.title || atlasStepTypeLabel(step),
  );
  const parentId =
    atlasEditorValue(root, "[data-live-parent]", step.parentId || "") || null;
  if ((parentId || null) !== (step.parentId || null))
    setStepParent(step, parentId);
  step.branchType = step.parentId
    ? atlasEditorValue(root, "[data-live-branch]", step.branchType || "then")
    : "root";
  step.enabled = !!atlasEditorValue(
    root,
    "[data-live-enabled]",
    step.enabled !== false,
  );
  step.notes = atlasEditorValue(
    root,
    "[data-step-notes-live]",
    step.notes || "",
  );
  atlasCaptureGuidedFields(root, step);
  normalizeCatalogStep?.(step);
  if (rerender) {
    if (typeof atlasRequestStructuralStepRender === "function") {
      atlasRequestStructuralStepRender();
    } else {
      renderSteps?.();
      renderSelectedStep?.();
      renderLogicTablePreviewRows?.();
      renderPreview?.();
      renderValidationPanel?.();
    }
  } else {
    const output = root.querySelector("[data-live-generated-output]");
    if (output) {
      output.innerHTML = renderLogicWithPills(analystLogic(step));
    }

    atlasRefreshLogicRuleCard(step);
    renderPreview?.();
    renderLogicTablePreviewRows?.();
    renderValidationPanel?.();
  }
  scheduleAutosave();
}
function renderLogicTablePreviewRows() {
  const target = $("logicBuilderTableBody");
  if (!target) return;
  const entries = atlasVisibleStepEntries();
  target.innerHTML = entries.length
    ? entries
        .map(
          (entry) =>
            `<tr class="${state.selectedStepId === entry.step.id ? "selected-row" : ""}" data-table-step-id="${esc(entry.step.id)}"><td>${esc(entry.number)}</td><td>${esc(atlasStepTypeLabel(entry.step))}</td><td>${renderLogicWithPills(analystLogic(entry.step))}</td><td>${entry.step.enabled === false ? '<span class="badge red">Disabled</span>' : '<span class="badge blue">Active</span>'}</td></tr>`,
        )
        .join("")
    : '<tr><td colspan="4" class="hint">No logic steps yet.</td></tr>';
}
function atlasRenderHiddenPreserveFields(step) {
  return `<div class="logic-rule-hidden-fields"><input type="hidden" data-step-parent value="${esc(step.parentId || "")}"><input type="hidden" data-step-branch value="${esc(step.branchType || (step.parentId ? "then" : "root"))}"><input type="hidden" data-step-title value="${esc(step.title || atlasStepTypeLabel(step))}"><input type="hidden" data-step-type value="${esc(step.step_type || "")}"><input type="hidden" data-step-source value="${esc(step.source || "")}"><input type="hidden" data-step-field value="${esc(step.field || "")}"><input type="hidden" data-step-action value="${esc(step.action || "")}"><textarea data-step-notes>${esc(step.notes || "")}</textarea><input type="checkbox" data-step-enabled ${step.enabled !== false ? "checked" : ""}></div>`;
}
