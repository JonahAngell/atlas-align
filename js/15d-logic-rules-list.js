const atlasCaptureGuidedFieldsBeforeMathUpdate = atlasCaptureGuidedFields;
atlasCaptureGuidedFields = function atlasCaptureGuidedFieldsWithMath(
  root,
  step,
) {
  root.querySelectorAll("[data-sort-editor]").forEach((editor) => {
    atlasSyncSortEditor?.(editor, { commit: false });
  });
  root.querySelectorAll("[data-math-editor]").forEach((editor) => {
    const hidden = editor.querySelector("[data-math-json]");
    if (hidden)
      hidden.value = atlasSerializeMathOperations(
        atlasMathOperationsFromContainer(editor),
      );
  });
  atlasCaptureGuidedFieldsBeforeMathUpdate(root, step);
  const conditionRows = [...root.querySelectorAll(".guided-condition-row")];
  if (!conditionRows.length) return;
  const conditions = conditionRows.map((row, index) => {
    const get = (field) =>
      row.querySelector(`[data-condition-field="${field}"]`)?.value || "";
    const sourceFile = get("sourceFile");
    const compareSourceFile = get("compareSourceFile") || sourceFile;
    const mathEditor = row.querySelector('[data-math-param="compareMathJson"]');
    const compareMathJson = mathEditor
      ? atlasSerializeMathOperations(
          atlasMathOperationsFromContainer(mathEditor),
        )
      : get("compareMathJson");
    return {
      id: row.dataset.conditionId || uid("cond"),
      connector: index === 0 ? "IF" : get("connector") || "AND",
      conditionType: "row_compare",
      sourceFile,
      sourceAlias: sourceAliasFor(sourceFile),
      fieldName: get("fieldName"),
      operator: get("operator") || "is equal to",
      valueMode: get("valueMode") || "values",
      compareValue: get("compareValue"),
      compareSourceFile,
      compareSourceAlias: sourceAliasFor(compareSourceFile),
      compareFieldName: get("compareFieldName"),
      expression: get("expression"),
      compareMathJson,
    };
  });
  atlasWriteLiveEditorConditions(step, conditions);
};
