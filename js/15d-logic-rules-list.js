function atlasStepTypeLabel(step) {
  return (
    (STEP_TYPE_OPTIONS || []).find(
      ([value]) => value === step.step_type,
    )?.[1] ||
    step.step_type ||
    "Logic Step"
  );
}
function atlasSelectOptions(options, selected) {
  return options
    .map((option) =>
      Array.isArray(option)
        ? `<option value="${esc(option[0])}" ${selected === option[0] ? "selected" : ""}>${esc(option[1])}</option>`
        : `<option value="${esc(option)}" ${selected === option ? "selected" : ""}>${esc(option)}</option>`,
    )
    .join("");
}
function atlasVisibleStepEntries() {
  return hierarchicalStepEntries({ includeDisabled: true });
}
function atlasEditorValue(root, selector, fallback = "") {
  const field = root.querySelector(selector);
  if (!field) return fallback;
  if (field.type === "checkbox") return field.checked;
  return field.value;
}
function atlasCaptureGuidedFields(root, step) {
  normalizeCatalogStep?.(step);
  step.params =
    step.params && typeof step.params === "object" ? step.params : {};
  root.querySelectorAll("[data-param]").forEach((input) => {
    const key = input.dataset.param;
    if (!key) return;
    step.params[key] =
      input.type === "checkbox" ? (input.checked ? "Yes" : "No") : input.value;
  });
  const conditionRows = [...root.querySelectorAll(".guided-condition-row")];
  if (conditionRows.length) {
    const conditions = conditionRows.map((row, index) => {
      const get = (field) =>
        row.querySelector(`[data-condition-field="${field}"]`)?.value || "";
      const sourceFile = get("sourceFile");
      const compareSourceFile = get("compareSourceFile") || sourceFile;
      return {
        id: row.dataset.conditionId || uid("cond"),
        connector: index === 0 ? "IF" : get("connector") || "AND",
        conditionType: "row_compare",
        sourceFile,
        sourceAlias: sourceAliasFor(sourceFile),
        fieldName: get("fieldName"),
        operator: get("operator") || "is equal to",
        valueMode: get("valueMode") || "values",
        compareValue: get("compareValue"),
        compareSourceFile,
        compareSourceAlias: sourceAliasFor(compareSourceFile),
        compareFieldName: get("compareFieldName"),
        expression: get("expression"),
      };
    });
    step.params.conditions_json = JSON.stringify(conditions);
    step.conditions = conditions.map((condition) => ({
      id: condition.id,
      field: condition.fieldName,
      operator: condition.operator,
      value: condition.compareValue,
    }));
  }
  if (step.params.source_file) {
    step.source = step.params.source_file;
    step.params.source_alias = sourceAliasFor(step.params.source_file);
  }
  if (step.params.field_name) step.field = step.params.field_name;
  if (step.params.column_name) step.field = step.params.column_name;
}
function atlasRefreshLogicRuleCard(step) {
  if (!step?.id) return;

  const card = document.querySelector(
    `.step-card[data-id="${CSS.escape(step.id)}"]`,
  );
  if (!card) return;

  const logicTarget = card.querySelector(
    ".compact-rule-logic, .logic-rule-summary",
  );
  if (logicTarget) {
    logicTarget.innerHTML = renderLogicWithPills(analystLogic(step));
  }

  card.classList.toggle("selected", state.selectedStepId === step.id);
}

function atlasCommitLiveEditor({ rerender = false } = {}) {
  const root = document.querySelector("[data-live-editor-step-id]");
  if (!root) return;
  const step = state.audit.steps.find(
    (item) => item.id === root.dataset.liveEditorStepId,
  );
  if (!step || step.autoGeneratedReference) return;
  const nextType = atlasEditorValue(
    root,
    "[data-live-step-type-select]",
    step.step_type || "if_then",
  );
  const typeChanged = nextType && nextType !== step.step_type;
  step.step_type = nextType;
  step.type = legacyTypeFromStepType?.(step.step_type) || step.type;
  if (typeChanged) {
    step.params = {};
    if (
      !["if_then", "else", "filter_rows", "flag_records"].includes(
        step.step_type,
      )
    )
      step.conditions = [];
    normalizeCatalogStep?.(step);
    if (typeof atlasRequestStructuralStepRender === "function") {
      atlasRequestStructuralStepRender();
    } else {
      renderSteps?.();
      renderSelectedStep?.();
      renderLogicTablePreviewRows?.();
      renderPreview?.();
      renderValidationPanel?.();
    }
    scheduleAutosave();
    return;
  }
  step.title = atlasEditorValue(
    root,
    "[data-live-step-title]",
    step.title || atlasStepTypeLabel(step),
  );
  const parentId =
    atlasEditorValue(root, "[data-live-parent]", step.parentId || "") || null;
  if ((parentId || null) !== (step.parentId || null))
    setStepParent(step, parentId);
  step.branchType = step.parentId
    ? atlasEditorValue(root, "[data-live-branch]", step.branchType || "then")
    : "root";
  step.enabled = !!atlasEditorValue(
    root,
    "[data-live-enabled]",
    step.enabled !== false,
  );
  step.notes = atlasEditorValue(
    root,
    "[data-step-notes-live]",
    step.notes || "",
  );
  atlasCaptureGuidedFields(root, step);
  normalizeCatalogStep?.(step);
  if (rerender) {
    if (typeof atlasRequestStructuralStepRender === "function") {
      atlasRequestStructuralStepRender();
    } else {
      renderSteps?.();
      renderSelectedStep?.();
      renderLogicTablePreviewRows?.();
      renderPreview?.();
      renderValidationPanel?.();
    }
  } else {
    const output = root.querySelector("[data-live-generated-output]");
    if (output) {
      output.innerHTML = renderLogicWithPills(analystLogic(step));
    }

    atlasRefreshLogicRuleCard(step);
    renderPreview?.();
    renderLogicTablePreviewRows?.();
    renderValidationPanel?.();
  }
  scheduleAutosave();
}
function atlasRenderParentOptions(step) {
  return parentOptionsForStep(step)
    .map(
      (option) =>
        `<option value="${esc(option.id)}" ${(step.parentId || "") === option.id ? "selected" : ""}>${esc(option.label)}</option>`,
    )
    .join("");
}
function atlasRenderBranchEditor(step) {
  if (!step.parentId)
    return '<input type="hidden" data-live-branch value="root"><p class="hint">Top-level rule. Use Indent to nest it under the previous rule.</p>';
  return `<label><span>Branch Type</span><select data-live-branch>${branchTypeOptions(step)}</select></label>`;
}
function atlasRenderStepEditor(step) {
  if (!step || step.autoGeneratedReference) {
    return '<div class="logic-editor-section"><p class="hint">Generated reference steps are controlled by selected source files. Select a manual rule to edit its logic criteria.</p></div>';
  }
  normalizeCatalogStep?.(step);
  return `<div class="logic-editor-form" data-live-editor-step-id="${esc(step.id)}">
    <section class="logic-editor-section">
      <h3>Step settings</h3>
      <div class="logic-editor-grid">
        <label class="full"><span>Step Name</span><input data-live-step-title value="${esc(step.title || atlasStepTypeLabel(step))}" placeholder="Name this rule"></label>
        <label><span>Step Type</span><select data-live-step-type-select>${atlasSelectOptions(
          (STEP_TYPE_OPTIONS || []).filter(
            ([value]) => value !== "reference_source",
          ),
          step.step_type,
        )}</select></label>
        <label><span>Parent Step</span><select data-live-parent>${atlasRenderParentOptions(step)}</select></label>
        ${atlasRenderBranchEditor(step)}
        <label><span class="check"><input type="checkbox" data-live-enabled ${step.enabled !== false ? "checked" : ""}> Enabled</span></label>
      </div>
      <div class="logic-editor-toolbar">
        <button type="button" class="btn secondary small" data-indent>Indent</button>
        <button type="button" class="btn secondary small" data-outdent>Outdent</button>
        <button type="button" class="btn secondary small" data-add-child-step>Add Child</button>
        <button type="button" class="btn danger small" data-delete-step>Delete</button>
      </div>
    </section>
    <section class="logic-editor-section">
      <h3>Criteria</h3>
      ${renderGuidedBuilder(step)}
    </section>
    <section class="logic-editor-section">
      <h3>Notes</h3>
      <label class="full"><span>Manual Notes</span><textarea data-step-notes-live placeholder="Notes for this step">${esc(step.notes || "")}</textarea></label>
    </section>
  </div>`;
}
renderSelectedStep = function renderSelectedStepEditorPane() {
  const step = state.audit.steps.find(
    (item) => item.id === state.selectedStepId,
  );
  const target = e.selectedStepDetails || $("selectedStepDetails");
  if (!target) return;
  if (!step) {
    target.innerHTML =
      '<p class="hint">Select or create a rule to edit step criteria.</p>';
    setText?.("selectedRuleBadge", "No rule selected");
    return;
  }
  const number = stepNumberFor(step.id) || "?";
  setText?.("selectedRuleBadge", `Step ${number}`);
  target.innerHTML = `<div class="logic-editor-header"><div class="logic-editor-header-main"><span class="badge blue">Step ${esc(number)}</span><strong>${esc(step.title || atlasStepTypeLabel(step))}</strong><span class="small">${esc(atlasStepTypeLabel(step))} · ${step.autoGeneratedReference ? "Generated reference step" : "Editable rule"}</span></div></div><div class="callout logic-editor-generated"><strong>Live Standardised Output</strong><div class="logic-output-text" data-live-generated-output>${renderLogicWithPills(analystLogic(step))}</div></div>${atlasRenderStepEditor(step)}`;
};
function renderLogicTablePreviewRows() {
  const target = $("logicBuilderTableBody");
  if (!target) return;
  const entries = atlasVisibleStepEntries();
  target.innerHTML = entries.length
    ? entries
        .map(
          (entry) =>
            `<tr class="${state.selectedStepId === entry.step.id ? "selected-row" : ""}" data-table-step-id="${esc(entry.step.id)}"><td>${esc(entry.number)}</td><td>${esc(atlasStepTypeLabel(entry.step))}</td><td>${renderLogicWithPills(analystLogic(entry.step))}</td><td>${entry.step.enabled === false ? '<span class="badge red">Disabled</span>' : '<span class="badge blue">Active</span>'}</td></tr>`,
        )
        .join("")
    : '<tr><td colspan="4" class="hint">No logic steps yet.</td></tr>';
}
function atlasRenderHiddenPreserveFields(step) {
  return `<div class="logic-rule-hidden-fields"><input type="hidden" data-step-parent value="${esc(step.parentId || "")}"><input type="hidden" data-step-branch value="${esc(step.branchType || (step.parentId ? "then" : "root"))}"><input type="hidden" data-step-title value="${esc(step.title || atlasStepTypeLabel(step))}"><input type="hidden" data-step-type value="${esc(step.step_type || "")}"><input type="hidden" data-step-source value="${esc(step.source || "")}"><input type="hidden" data-step-field value="${esc(step.field || "")}"><input type="hidden" data-step-action value="${esc(step.action || "")}"><textarea data-step-notes>${esc(step.notes || "")}</textarea><input type="checkbox" data-step-enabled ${step.enabled !== false ? "checked" : ""}></div>`;
}
const atlasPreviousSetPickerTargetValue =
  typeof setPickerTargetValue === "function" ? setPickerTargetValue : null;
setPickerTargetValue = function setPickerTargetValueEditorAware(
  value,
  sourceFile = "",
) {
  const target = visualPickerState?.target;
  if (!target) return;
  const container =
    target.closest(".step-card") ||
    target.closest(".guided-condition-row") ||
    target.closest("[data-live-editor-step-id]");
  if (visualPickerState.targetType === "condition") {
    const hidden = container?.querySelector(
      `[data-condition-field="${CSS.escape(visualPickerState.name)}"]`,
    );
    if (hidden) hidden.value = value;
    if (visualPickerState.kind === "field") {
      const sourceHidden = container?.querySelector(
        '[data-condition-field="sourceFile"]',
      );
      if (sourceHidden && !sourceHidden.value) sourceHidden.value = sourceFile;
    }
  } else {
    const hidden = container?.querySelector(
      `[data-param="${CSS.escape(visualPickerState.name)}"]`,
    );
    if (hidden) hidden.value = value;
    if (visualPickerState.kind === "field") {
      const sourceHidden = container?.querySelector(
        '[data-param="source_file"]',
      );
      if (sourceHidden && !sourceHidden.value) sourceHidden.value = sourceFile;
    }
  }
  visualPickerState = null;
  document
    .querySelector(".visual-picker-modal-backdrop.dynamic-mini-picker")
    ?.remove();
  atlasCommitLiveEditor({ rerender: true });
};
document.addEventListener(
  "change",
  (event) => {
    const root = event.target.closest("[data-live-editor-step-id]");
    if (!root) return;
    atlasCommitLiveEditor({
      rerender: event.target.matches(
        '[data-live-step-type-select], [data-live-parent], [data-live-branch], [data-param="source_file"], [data-condition-field="sourceFile"], [data-condition-field="valueMode"]',
      ),
    });
  },
  true,
);
document.addEventListener(
  "input",
  (event) => {
    const root = event.target.closest("[data-live-editor-step-id]");
    if (!root) return;
    atlasCommitLiveEditor({ rerender: false });
  },
  true,
);
document.addEventListener(
  "click",
  (event) => {
    const card = event.target.closest(".logic-rule-card");
    const interactiveControl = event.target.closest(
      "button, input, select, textarea, a, summary, [data-rule-menu-toggle], [data-rule-menu-panel]",
    );
    if (card && !interactiveControl) {
      state.selectedStepId = card.dataset.id;
      renderSteps();
      atlasRevealLogicStepPane?.();
      return;
    }
    const tableRow = event.target.closest("[data-table-step-id]");
    if (tableRow) {
      state.selectedStepId = tableRow.dataset.tableStepId;
      renderSteps();
      atlasRevealLogicStepPane?.();
    }
  },
  true,
);

