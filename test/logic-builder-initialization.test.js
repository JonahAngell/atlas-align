test("reference children limit the visual picker to the reference source", () => {
  const steps = {
    ref: {
      id: "ref",
      parentId: null,
      step_type: "reference_source",
      autoGeneratedReference: true,
      source: "Orders",
      params: { source_file: "orders.csv" },
    },
    child: { id: "child", parentId: "ref", step_type: "if_then", params: {} },
    nested: {
      id: "nested",
      parentId: "child",
      step_type: "create_column",
      params: {},
    },
    root: { id: "root", parentId: null, step_type: "if_then", params: {} },
  };
  const context = vm.createContext({
    stepById: (id) => steps[id],
    pickerSourceOptions: () => [
      { sourceFile: "orders.csv", sourceAlias: "orders" },
      { sourceFile: "customers.csv", sourceAlias: "customers" },
    ],
    visualPickerState: null,
    state: { selectedStepId: "child" },
  });
  vm.runInContext(
    [
      functionSource(
        "../js/15g-visual-ui-events.js",
        "atlasPickerReferenceSource",
      ),
      functionSource(
        "../js/15g-visual-ui-events.js",
        "atlasReferenceChildSource",
      ),
      functionSource(
        "../js/15g-visual-ui-events.js",
        "atlasPickerSourceMatches",
      ),
      functionSource(
        "../js/15g-visual-ui-events.js",
        "atlasFieldPickerEligibilityPolicy",
      ),
      `pickerSourceOptions = function pickerSourceOptionsForReferenceChildren() {
        const options = [
          { sourceFile: "orders.csv", sourceAlias: "orders" },
          { sourceFile: "customers.csv", sourceAlias: "customers" },
        ];
        const referenceSource = atlasReferenceChildSource(stepById(visualPickerState?.targetStepId || state.selectedStepId));
        if (!referenceSource) return options;
        return options.filter((option) => atlasPickerSourceMatches(option, referenceSource));
      };`,
    ].join("\n"),
    context,
  );
  const childPolicy = context.atlasFieldPickerEligibilityPolicy(
    { dataset: { openMiniPicker: "field", conditionName: "fieldName" } },
    steps.child,
  );
  assert.equal(childPolicy.mode, "reference-source");
  assert.equal(childPolicy.sourceFile, "orders.csv");
  assert.equal(
    context.atlasFieldPickerEligibilityPolicy(
      { dataset: { openMiniPicker: "field", paramName: "concat_field_1" } },
      steps.nested,
    ).sourceFile,
    "orders.csv",
  );
  assert.equal(
    context.atlasFieldPickerEligibilityPolicy(
      {
        dataset: { openMiniPicker: "field", conditionName: "compareFieldName" },
        closest: () => true,
      },
      steps.root,
    ).mode,
    "all-selected",
  );
  context.visualPickerState = { targetStepId: "child" };
  assert.equal(
    context
      .pickerSourceOptions()
      .map((option) => option.sourceFile)
      .join(","),
    "orders.csv",
  );
});

