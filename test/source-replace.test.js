import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";

const source = readFileSync(
  new URL("../js/15i-source-replace.js", import.meta.url),
  "utf8",
);

function load() {
  const sandbox = { console };
  sandbox.window = sandbox;
  const context = vm.createContext(sandbox);
  vm.runInContext(source, context);
  return context;
}

const replacement = load();

test("auto-match prefers one exact raw name and leaves ties unmatched", () => {
  const employee = {
    sourceKey: "B",
    sourceFile: "Source B",
    alias: "B",
    field: "Employee",
    vanity: "Employee ID",
    matchingKeys: ["person"],
  };
  const worker = {
    sourceKey: "C",
    sourceFile: "Source C",
    alias: "C",
    field: "Worker",
    vanity: "Person",
    matchingKeys: ["person"],
  };
  assert.equal(
    replacement.atlasAutoMatchSourceReplacement(
      { field: "Employee", vanity: "Emp", matchingKeys: [] },
      [employee, worker],
    ).sourceKey,
    "B",
  );
  assert.equal(
    replacement.atlasAutoMatchSourceReplacement(
      { field: "Employee", vanity: "Emp", matchingKeys: [] },
      [employee, { ...worker, field: "Employee" }],
    ),
    null,
  );
});

test("auto-match uses case-insensitive names, then vanity, then a unique matching key", () => {
  const employee = {
    sourceKey: "B",
    sourceFile: "Source B",
    alias: "B",
    field: "Employee",
    vanity: "Employee ID",
    matchingKeys: ["person"],
  };
  const other = {
    sourceKey: "C",
    sourceFile: "Source C",
    alias: "C",
    field: "Worker",
    vanity: "Person",
    matchingKeys: ["other"],
  };
  assert.equal(
    replacement.atlasAutoMatchSourceReplacement(
      { field: "employee", vanity: "employee", matchingKeys: [] },
      [employee, other],
    ).field,
    "Employee",
  );
  assert.equal(
    replacement.atlasAutoMatchSourceReplacement(
      { field: "emp_no", vanity: "Employee ID", matchingKeys: [] },
      [{ ...employee, field: "raw_emp" }, other],
    ).sourceKey,
    "B",
  );
  assert.equal(
    replacement.atlasAutoMatchSourceReplacement(
      { field: "x", vanity: "x", matchingKeys: ["person"] },
      [
        { ...employee, field: "no", vanity: "no" },
        { ...other, field: "nope", vanity: "nope" },
      ],
    ).sourceKey,
    "B",
  );
  assert.equal(
    replacement.atlasAutoMatchSourceReplacement(
      { field: "x", vanity: "x", matchingKeys: ["person"] },
      [employee, { ...other, matchingKeys: ["person"] }],
    ),
    null,
  );
});

test("a step can map fields onto two sources while an unmatched field stays put", () => {
  const audit = {
    sources: [{ sourceKey: "A", sourceFile: "Source A", color: "#111111" }],
    displayFields: [
      { sourceKey: "A", sourceFile: "Source A", fieldName: "Employee" },
    ],
    steps: [
      {
        id: "join-1",
        step_type: "join",
        params: {
          left_source: "A",
          left_field: "Employee",
          right_source: "A",
          right_field: "CostCenter",
          conditions_json: JSON.stringify([
            {
              sourceFile: "A",
              fieldName: "Unmatched",
              operator: "is equal to",
              valueMode: "values",
              compareValue: "x",
            },
          ]),
        },
      },
      {
        id: "generated",
        autoGeneratedReference: true,
        source: "A",
        field: "SkipMe",
        params: { source_file: "A", field_name: "SkipMe" },
      },
    ],
  };
  const rows = replacement.atlasCollectSourceReplacementRows(audit, {
    sourceKey: "A",
    sourceFile: "Source A",
  });
  assert.equal(
    rows
      .map((row) => row.field)
      .sort()
      .join("|"),
    "CostCenter|Employee|Unmatched",
  );
  replacement.atlasRewriteSourceReplacementReferences(
    audit,
    { sourceKey: "A", sourceFile: "Source A" },
    [
      {
        oldField: "Employee",
        destination: {
          sourceKey: "B",
          sourceFile: "Source B",
          alias: "B",
          field: "Emp ID",
        },
      },
      {
        oldField: "CostCenter",
        destination: {
          sourceKey: "C",
          sourceFile: "Source C",
          alias: "C",
          field: "CC",
        },
      },
      { oldField: "Unmatched", destination: null },
    ],
    [
      { sourceKey: "B", sourceFile: "Source B" },
      { sourceKey: "C", sourceFile: "Source C" },
    ],
  );
  assert.equal(audit.steps[0].params.left_source, "B");
  assert.equal(audit.steps[0].params.left_field, "Emp ID");
  assert.equal(audit.steps[0].params.right_source, "C");
  assert.equal(audit.steps[0].params.right_field, "CC");
  const conditions = JSON.parse(audit.steps[0].params.conditions_json);
  assert.equal(conditions[0].sourceFile, "A");
  assert.equal(conditions[0].fieldName, "Unmatched");
  assert.equal(audit.steps[1].source, "A");
  assert.equal(audit.steps[1].field, "SkipMe");
  assert.equal(audit.displayFields[0].sourceKey, "B");
  assert.equal(audit.displayFields[0].fieldName, "Emp ID");
});

test("gaps keep unmatched fields and replacement sources that received no mapping", () => {
  const existing = {
    fields: [{ originalSourceKey: "Z", originalField: "Keep" }],
    sources: [],
  };
  const gaps = replacement.atlasBuildSourceReplacementGaps({
    original: { sourceKey: "A", sourceFile: "Source A" },
    rows: [
      { field: "Employee", destination: { sourceKey: "B" } },
      { field: "Unmatched", destination: null },
    ],
    replacementSources: [
      { sourceKey: "B", sourceFile: "Source B" },
      { sourceKey: "C", sourceFile: "Source C" },
    ],
    existing,
  });
  assert.equal(
    gaps.fields.map((item) => item.originalField).join("|"),
    "Keep|Unmatched",
  );
  assert.equal(gaps.sources.length, 1);
  assert.equal(gaps.sources[0].sourceKey, "C");
  assert.equal(gaps.sources[0].replacedSourceKey, "A");

  const finished = replacement.atlasBuildSourceReplacementGaps({
    original: { sourceKey: "A", sourceFile: "Source A" },
    rows: [
      { field: "Employee", destination: { sourceKey: "B" } },
      { field: "Unmatched", destination: { sourceKey: "C" } },
    ],
    replacementSources: [
      { sourceKey: "B", sourceFile: "Source B" },
      { sourceKey: "C", sourceFile: "Source C" },
    ],
    existing: gaps,
  });
  assert.equal(finished.fields.map((item) => item.originalField).join("|"), "Keep");
  assert.equal(finished.sources.length, 0);

  const unusedSwap = replacement.atlasBuildSourceReplacementGaps({
    original: { sourceKey: "A", sourceFile: "Source A" },
    rows: [],
    replacementSources: [
      { sourceKey: "B", sourceFile: "Source B" },
      { sourceKey: "C", sourceFile: "Source C" },
    ],
    existing: { fields: [], sources: [] },
  });
  assert.equal(unusedSwap.fields.length, 0);
  assert.equal(unusedSwap.sources.length, 0);
});
