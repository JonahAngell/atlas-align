/**
 * Step capabilities read from the definition (Phase 10, issue 5045 of the
 * Dynamic Step Type Builder plan): carrying conditions, THEN / ELSE branches,
 * the linked inverse and the business order group.
 *
 * The bundled versions do not declare the new keys, so the engine answers
 * for them from a legacy table; a builder type that declares them is treated
 * like IF / THEN in the complete statements.
 */
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
import { loadApp } from "./support/step-type-harness.js";

const read = (file) =>
  JSON.parse(readFileSync(new URL(`../${file}`, import.meta.url), "utf8"));
const run = (context, code) => vm.runInContext(code, context);
const plain = (value) => JSON.parse(JSON.stringify(value ?? null));

const capabilities = (context, definition, typeId) => {
  context.__definition = definition ?? null;
  context.__typeId = typeId;
  return plain(
    run(
      context,
      "ATLASStepTypes.definitions.capabilities(__definition, __typeId)",
    ),
  );
};

/** IF / THEN as a builder type with its own id and the new keys declared. */
function checkRule() {
  const definition = structuredClone(read("catalogs/step-types/if_then.json"));
  definition.id = "check_rule";
  definition.label = "Check Rule";
  delete definition.aliases; // "if" and "compare" belong to if_then
  delete definition.referenceChild;
  definition.branches = ["then", "else"];
  definition.inverse = true;
  return definition;
}

test("bundled types keep today's capabilities", async () => {
  const context = await loadApp();
  const expected = {
    if_then: [true, true, ["then", "else"], true, 40, true],
    else: [true, false, [], false, 40, false],
    filter_rows: [true, false, [], false, 40, false],
    flag_records: [true, false, [], false, 40, false],
    reference_source: [false, false, [], false, 10, false],
    join: [false, false, [], false, 20, false],
    create_column: [false, false, [], false, 30, true],
    union_sources: [false, false, [], false, 40, false],
    split_field: [false, false, [], false, 40, false],
  };
  for (const [id, values] of Object.entries(expected)) {
    const definition = read(`catalogs/step-types/${id}.json`);
    const [
      carriesConditions,
      storesConditions,
      branches,
      inverse,
      group,
      referenceChild,
    ] = values;
    assert.deepEqual(
      capabilities(context, definition),
      {
        carriesConditions,
        storesConditions,
        branches,
        inverse,
        orderGroup: group,
        referenceChild,
      },
      id,
    );
  }
});

test("declared keys win over the legacy answers", async () => {
  const context = await loadApp();
  const found = capabilities(context, checkRule());
  assert.deepEqual(found, {
    carriesConditions: true,
    storesConditions: true,
    branches: ["then", "else"],
    inverse: true,
    orderGroup: 40,
    referenceChild: false,
  });
  const quiet = {
    ...checkRule(),
    branches: [],
    inverse: false,
    orderGroup: 30,
  };
  assert.deepEqual(capabilities(context, quiet), {
    carriesConditions: true,
    storesConditions: true,
    branches: [],
    inverse: false,
    orderGroup: 30,
    referenceChild: false,
  });
});

test("a linked inverse needs branches and a Conditions field", async () => {
  const context = await loadApp();
  context.__definition = {
    ...read("catalogs/step-types/create_column.json"),
    id: "inverse_only",
    inverse: true,
  };
  const errors = plain(
    run(
      context,
      "ATLASStepTypes.definitions.validate(__definition, { schema: ATLASStepTypes.bundled.schema }).errors",
    ),
  );
  const messages = errors
    .filter((error) => error.path === "/inverse")
    .map((error) => error.message);
  assert.ok(
    messages.some((message) => /branches/.test(message)),
    messages,
  );
  assert.ok(
    messages.some((message) => /Conditions/.test(message)),
    messages,
  );
});

test("the runtime reads capabilities from the step's definition", async () => {
  const context = await loadApp();
  const found = (step) => {
    context.__step = step;
    return plain(run(context, "atlasStepCapabilities(__step)"));
  };
  assert.equal(found({ step_type: "if_then" }).inverse, true);
  assert.equal(found({ type: "if" }).storesConditions, true);
  assert.equal(found({ step_type: "join" }).orderGroup, 20);
  assert.equal(
    found({ step_type: "join", autoGeneratedReference: true }).orderGroup,
    10,
  );
  assert.equal(found({ step_type: "else" }).carriesConditions, true);
  assert.equal(found({ step_type: "else" }).storesConditions, false);
});

