async function previewFor(parentType) {
  const context = await loadApp();
  context.__extra = [checkRule()];
  run(
    context,
    `(() => {
      const bundled = ATLASStepTypes.bundled;
      ATLASStepTypeRuntime.loadBundled({
        ...bundled,
        definitions: [...bundled.definitions, ...__extra],
      });
    })()`,
  );
  context.__document = audit(parentType);
  run(
    context,
    `state.audit = normalizeLoadedAudit(__document, "repo"); state.auditSelected = true;`,
  );
  return {
    capabilities: plain(
      run(context, "atlasStepCapabilities(state.audit.steps[0])"),
    ),
    rows: plain(run(context, "completeStatementPreviewRows()")),
  };
}

test("a builder type with Conditions, branches and inverse reads like IF / THEN", async () => {
  const builder = await previewFor("check_rule");
  const ifThen = await previewFor("if_then");
  assert.equal(builder.capabilities.storesConditions, true);
  assert.deepEqual(builder.capabilities.branches, ["then", "else"]);
  assert.ok(ifThen.rows.length >= 2, "IF / THEN children are shown");
  assert.deepEqual(builder.rows, ifThen.rows);
});
